import AppKit
import ApplicationServices
import Carbon
import Foundation

@MainActor
struct TextInjector {
    /// How long to wait for the target app to read the pasteboard before restoring the user's clipboard.
    var restoreDelay: Duration = .milliseconds(600)

    /// Marker types from nspasteboard.org; clipboard managers skip items that carry them.
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    static func copyToClipboard(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    func hasAccessibilityPermission(promptIfNeeded: Bool) -> Bool {
        if promptIfNeeded {
            let options = ["AXTrustedCheckOptionPrompt" as CFString: true] as CFDictionary
            return AXIsProcessTrustedWithOptions(options)
        }

        return AXIsProcessTrusted()
    }

    /// Pastes `text` into the focused app with a synthetic Cmd+V, then puts the previous clipboard back.
    func inject(text: String) async throws {
        guard hasAccessibilityPermission(promptIfNeeded: true) else {
            throw TextInjectionError.accessibilityPermissionMissing
        }

        guard
            let source = CGEventSource(stateID: .combinedSessionState),
            let commandVDown = CGEvent(keyboardEventSource: source, virtualKey: UInt16(kVK_ANSI_V), keyDown: true),
            let commandVUp = CGEvent(keyboardEventSource: source, virtualKey: UInt16(kVK_ANSI_V), keyDown: false)
        else {
            throw TextInjectionError.eventCreationFailed
        }

        let pasteboard = NSPasteboard.general
        let snapshot = PasteboardSnapshot(pasteboard: pasteboard)

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: Self.transientType)
        item.setData(Data(), forType: Self.autoGeneratedType)
        pasteboard.writeObjects([item])
        let injectedChangeCount = pasteboard.changeCount

        commandVDown.flags = .maskCommand
        commandVUp.flags = .maskCommand
        commandVDown.post(tap: .cghidEventTap)
        commandVUp.post(tap: .cghidEventTap)

        try? await Task.sleep(for: restoreDelay)

        // Only restore if nothing else has written to the clipboard in the meantime.
        if pasteboard.changeCount == injectedChangeCount {
            snapshot.restore(to: pasteboard)
        }
    }
}

/// A copy of every item and type on a pasteboard, so it can be written back later.
struct PasteboardSnapshot {
    private let items: [[NSPasteboard.PasteboardType: Data]]

    init(pasteboard: NSPasteboard) {
        items = (pasteboard.pasteboardItems ?? []).map { item in
            var representations: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) {
                    representations[type] = data
                }
            }
            return representations
        }
    }

    var isEmpty: Bool { items.isEmpty }

    func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }

        let restored = items.map { representations in
            let item = NSPasteboardItem()
            for (type, data) in representations {
                item.setData(data, forType: type)
            }
            return item
        }
        pasteboard.writeObjects(restored)
    }
}

enum TextInjectionError: LocalizedError {
    case accessibilityPermissionMissing
    case eventCreationFailed

    var errorDescription: String? {
        switch self {
        case .accessibilityPermissionMissing:
            return "Accessibility permission is required to paste into other apps."
        case .eventCreationFailed:
            return "Failed to synthesize Cmd+V key events."
        }
    }
}
